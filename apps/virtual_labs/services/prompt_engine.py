"""Prompt Engine (ТЗ, п. 25): анализ структуры промпта по 8 блокам
РОЛЬ → КОНТЕКСТ → ЦЕЛИ ОБУЧЕНИЯ → ЗАДАЧА → АУДИТОРИЯ → ФОРМАТ → ОГРАНИЧЕНИЯ → КРИТЕРИИ КАЧЕСТВА."""
import re

I = re.IGNORECASE

BLOCKS = [
    {"key": "role", "label": "РОЛЬ", "hint": "Укажите, в какой роли должен выступать ИИ (например, «опытный методист вуза»).",
     "re": [r"(^|\n)\s*(роль|role)\s*:", r"(^|[^а-яё])ты\s*[—–-]?\s*(опытн|эксперт|преподават|методист|учител|научн|специалист|редактор|сценарист|тьютор|наставник)", r"выступи в роли|в роли "]},
    {"key": "context", "label": "КОНТЕКСТ", "hint": "Опишите дисциплину, курс, язык и условия проведения занятия.",
     "re": [r"(^|\n)\s*(контекст|context)\s*:", r"дисциплин[аеыу]", r"в рамках (курса|предмета)"]},
    {"key": "objectives", "label": "ЦЕЛИ ОБУЧЕНИЯ", "hint": "Перечислите результаты обучения: что обучающиеся должны знать и уметь.",
     "re": [r"(^|\n)\s*(цели обучения|learning objectives)\s*:", r"результат[а-яёa-z]* обучени", r"(будут|должны) (знать|уметь)"]},
    {"key": "task", "label": "ЗАДАЧА", "hint": "Сформулируйте конкретное действие: что именно нужно создать.",
     "re": [r"(^|\n)\s*(задача|task)\s*:", r"(^|[^а-яё])(создай|разработай|сформируй|составь|подготовь|напиши|сгенерируй|оцени|проанализируй)"]},
    {"key": "audience", "label": "АУДИТОРИЯ", "hint": "Укажите, для кого материал: уровень и возраст обучающихся.",
     "re": [r"(^|\n)\s*(аудитория|audience)\s*:", r"для (студент|учащ|школьник|магистрант|слушател|преподават|учител)"]},
    {"key": "format", "label": "ФОРМАТ", "hint": "Задайте структуру ответа: разделы, заголовки, таблицы, объём.",
     "re": [r"(^|\n)\s*(формат|format)\s*:", r"(структур|раздел|заголов)[а-яёa-z]*", r"в виде (таблиц|списк)"]},
    {"key": "constraints", "label": "ОГРАНИЧЕНИЯ", "hint": "Добавьте ограничения: объём, язык, запрет выдуманных источников и фактов.",
     "re": [r"(^|\n)\s*(ограничения|constraints)\s*:", r"не (выдумывай|придумывай|используй|добавляй)", r"не более|объ[её]м"]},
    {"key": "criteria", "label": "КРИТЕРИИ КАЧЕСТВА", "hint": "Опишите, по каким критериям будет проверяться результат.",
     "re": [r"(^|\n)\s*(критерии качества|quality criteria)\s*:", r"критери[а-яёa-z]* (качеств|оцен)", r"провер[а-яёa-z]* (себя|результат)"]},
]
for _b in BLOCKS:
    _b["compiled"] = [re.compile(r, I) for r in _b["re"]]


def analyze(text: str) -> dict:
    """Какие блоки есть в промпте, оценка структуры 0–100 и советы по улучшению."""
    t = text or ""
    present, missing = [], []
    for b in BLOCKS:
        (present if any(r.search(t) for r in b["compiled"]) else missing).append(b["key"])
    n_words = len(re.findall(r"\S+", t))
    score = int((len(present) * 100 + len(BLOCKS) // 2) // len(BLOCKS))  # как Math.round(доля * 100) в интерфейсе
    if n_words < 15:
        score = min(score, 20)
    tips = [next(b["hint"] for b in BLOCKS if b["key"] == k) for k in missing]
    if n_words < 30:
        tips.append("Промпт слишком короткий: модель «додумает» недостающее сама, и результат будет шаблонным.")
    return {"present": present, "missing": missing, "score": score, "words": n_words, "tips": tips}
